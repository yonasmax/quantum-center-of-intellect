// Progress tracking ? reads user from Supabase Auth session
import { supabase } from '../supabaseClient';

// Get the currently-logged-in user's email from Supabase Auth
async function getUserId() {
  try {
    const { data: { session } } = await supabase.auth.getSession();
    if (session?.user?.email) {
      return session.user.email.toLowerCase().trim();
    }
  } catch (e) {
    console.warn('[progress] Session read failed:', e.message);
  }
  return null;
}

// ???????????????????????????????????????????????????????????
// MARK LESSON COMPLETE
// ???????????????????????????????????????????????????????????
export const markLessonComplete = async (lessonId, timeSpentSeconds = 0, courseId = null, lessonMeta = {}) => {
  const userId = await getUserId();
  console.log('[progress] Saving lesson:', lessonId, 'for user:', userId);

  if (!userId) {
    throw new Error('Not authenticated');
  }

  const { data, error } = await supabase
    .from('progress')
    .upsert(
      {
        user_id: userId,
        lesson_id: lessonId,
        lesson_title: lessonMeta.title || null,
        lesson_subject: lessonMeta.subject || null,
        completed: true,
        completed_at: new Date().toISOString(),
        time_spent_seconds: timeSpentSeconds,
      },
      { onConflict: 'user_id,lesson_id' }
    )
    .select()
    .single();

  if (error) {
    console.error('[progress] Save error:', error);
    throw error;
  }
  console.log('[progress] Saved:', data);
  return { data: { success: true, progress: data } };
};

